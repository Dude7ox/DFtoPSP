#!/usr/bin/env python3
"""Generate src/core/ItemData.cpp from the classic item template table.

Inputs (both MIT-licensed Daggerfall Unity reference copies, kept verbatim in
tools/ref/ so the table can be regenerated after modding or upstream fixes):
  tools/ref/ItemTemplates.txt  - the 288 classic item templates as JSON
  tools/ref/ItemEnums.cs       - the per-group item enums (enum value == template index)

Output:
  src/core/ItemData.cpp        - template table, group boundaries, enum constants

The port reads original game data at runtime; this table only describes the
*definitions* shipped with the original executable (prices, weights, icon
records), exactly like Daggerfall Unity's baked Resources/ItemTemplates.txt.
"""
import json
import re
import sys
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TPL = os.path.join(HERE, "ref", "ItemTemplates.txt")
ENUMS = os.path.join(HERE, "ref", "ItemEnums.cs")
OUT = os.path.join(HERE, "..", "src", "core", "ItemDataGen.cpp")
HOUT = os.path.join(HERE, "..", "src", "core", "ItemDefs.h")

# ItemGroups order, values from ItemEnums.cs
GROUPS = ["Drugs", "UselessItems1", "Armor", "Weapons", "MagicItems", "Artifacts",
          "MensClothing", "Books", "Furniture", "UselessItems2", "ReligiousItems",
          "Maps", "WomensClothing", "Paintings", "Gems", "PlantIngredients1",
          "PlantIngredients2", "CreatureIngredients1", "CreatureIngredients2",
          "CreatureIngredients3", "MiscellaneousIngredients1", "MetalIngredients",
          "MiscellaneousIngredients2", "Transportation", "Deeds", "Jewellery",
          "QuestItems", "MiscItems", "Currency"]
# enum type name in ItemEnums.cs per group, when one exists
GROUP_ENUM = {
    "Drugs": "Drugs", "UselessItems1": "UselessItems1", "Armor": "Armor",
    "Weapons": "Weapons", "MagicItems": "MagicItems", "Artifacts": "Artifacts",
    "MensClothing": "MensClothing", "Books": "Books", "Furniture": "Furniture",
    "UselessItems2": "UselessItems2", "ReligiousItems": "ReligiousItems",
    "Maps": "Maps", "WomensClothing": "WomensClothing", "Paintings": "Paintings",
    "Gems": "Gems", "PlantIngredients1": "PlantIngredients1",
    "PlantIngredients2": "PlantIngredients2", "CreatureIngredients1": "CreatureIngredients1",
    "CreatureIngredients2": "CreatureIngredients2", "CreatureIngredients3": "CreatureIngredients3",
    "MiscellaneousIngredients1": "MiscellaneousIngredients1", "MetalIngredients": "MetalIngredients",
    "MiscellaneousIngredients2": "MiscellaneousIngredients2", "Transportation": "Transportation",
    "Deeds": "Deeds", "Jewellery": "Jewellery", "QuestItems": "QuestItems",
    "MiscItems": "MiscItems", "Currency": "Currency",
}


def load_templates():
    lines = [l for l in open(TPL).read().splitlines() if not l.strip().startswith("//")]
    data = json.loads("\n".join(lines))
    data.sort(key=lambda t: t["index"])
    return data


def load_enums():
    src = open(ENUMS).read()
    src = "\n".join(l for l in src.splitlines() if not l.strip().startswith("//"))
    enums = {}
    for m in re.finditer(r"public enum (\w+)[^\{]*\{(.*?)\n    \}", src, re.S):
        name, body = m.group(1), m.group(2)
        vals = {}
        for em in re.finditer(r"(\w+)\s*=\s*(-?\w+)", body):
            v = em.group(2)
            vals[em.group(1)] = int(v, 0)
        enums[name] = vals
    return enums


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def cname(s):
    out = []
    for ch in s:
        out.append(ch if ch.isalnum() else "_")
    s = "".join(out)
    if s and s[0].isdigit():
        s = "_" + s
    return s


def main():
    tpls = load_templates()
    enums = load_enums()
    assert len(tpls) == 288 and tpls[0]["index"] == 0 and tpls[287]["index"] == 287
    # group boundaries: smallest enum value of each group's enum
    group_vals=[]
    for g in GROUPS:
        e=enums.get(GROUP_ENUM[g],{})
        group_vals.append(sorted(set(e.values())))

    def group_of(idx):
        for gi,vals in enumerate(group_vals):
            if idx in vals:
                return gi
        return -1


    with open(OUT, "w") as f:
        f.write('// GENERATED by tools/gen_item_data.py - do not edit by hand.\n')
        f.write('// Template data (c) the original Daggerfall executable, table layout\n')
        f.write('// from Daggerfall Unity (MIT). Regenerate with: python3 tools/gen_item_data.py\n')
        f.write('#include "ItemData.h"\nnamespace dfpsp {\n')
        f.write("const int kTemplateCount=%d;\n" % len(tpls))
        f.write("static const ItemTemplate kTemplates[kTemplateCount]={\n")
        for t in tpls:
            flags = (1 if t.get("isBluntWeapon") else 0) | (2 if t.get("isLiquid") else 0) \
                | (4 if t.get("isOneHanded") else 0) | (8 if t.get("isIngredient") else 0)
            f.write("{%s,%.3f,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d},\n" % (
                cstr(t["name"]), float(t["baseWeight"]), int(t["hitPoints"]),
                int(t["capacityOrTarget"]), int(t["basePrice"]), int(t["enchantmentPoints"]),
                int(t["rarity"]), int(t["variants"]), int(t["drawOrderOrEffect"]), flags,
                int(t["worldTextureArchive"]), int(t["worldTextureRecord"]),
                int(t["playerTextureArchive"]), int(t["playerTextureRecord"])))
        f.write("};\n")
        f.write("const ItemTemplate& itemTemplate(int i){return kTemplates[i<0?0:(i>=kTemplateCount?kTemplateCount-1:i)];}\n")
        flat=[]
        offs=[0]
        for vals in group_vals:
            flat.extend(vals)
            offs.append(len(flat))
        f.write("static const int kGroupValues[%d]={%s};\n" % (max(1,len(flat)), ",".join(str(v) for v in flat) if flat else "0"))
        f.write("static const int kGroupOff[kGroupCount+1]={%s};\n" % ",".join(str(o) for o in offs))
        f.write("int itemGroupOf(int idx){for(int g=0;g<kGroupCount;g++)for(int i=kGroupOff[g];i<kGroupOff[g+1];i++)if(kGroupValues[i]==idx)return g;return -1;}\n")
        f.write("int itemOrdinalInGroup(int idx){int g=itemGroupOf(idx);if(g<0)return -1;for(int i=kGroupOff[g];i<kGroupOff[g+1];i++)if(kGroupValues[i]==idx)return i-kGroupOff[g];return -1;}\n")
        f.write("int itemTemplateOfOrdinal(int group,int ordinal){if(group<0||group>=kGroupCount)return -1;if(ordinal<0||ordinal>=kGroupOff[group+1]-kGroupOff[group])return -1;return kGroupValues[kGroupOff[group]+ordinal];}\n")
        f.write("static const char* const kGroupNames[kGroupCount]={%s};\n" % ",".join(cstr(g) for g in GROUPS))
        f.write('const char* itemGroupName(int g){return g<0||g>=kGroupCount?"Misc":kGroupNames[g];}\n')
        f.write("} // namespace dfpsp\n")
    # enum constants as one prefixed enum in its own header
    with open(HOUT, "w") as f:
        f.write("// GENERATED by tools/gen_item_data.py - do not edit by hand.\n")
        f.write("// Enum value == classic template index; names prefixed by group.\n")
        f.write("#pragma once\nnamespace dfpsp {\nnamespace ItemDef {\nenum ItemDefEnum {\n")
        seen = {}
        for gi, g in enumerate(GROUPS):
            e = enums.get(GROUP_ENUM[g], {})
            for name, val in sorted(e.items(), key=lambda kv: kv[1]):
                key = cname(g + "_" + name)
                if key in seen:
                    key = cname(g + "_" + name + "_%d" % val)
                seen[key] = val
                f.write("%s=%d,\n" % (key, val))
        f.write("};\n}\n}\n")
    print("wrote %s: %d templates, %d groups, %d enum constants" % (
        os.path.normpath(OUT), len(tpls), len(GROUPS),
        sum(len(enums.get(GROUP_ENUM[g], {})) for g in GROUPS)))


if __name__ == "__main__":
    sys.exit(main())
